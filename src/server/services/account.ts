import "server-only";
import { prisma } from "../db";
import { deleteFile } from "../storage";

/** Removes every private file the student uploaded (database rows cascade with the user). */
export async function deleteUserFiles(userId: string) {
  const files = await prisma.storedFile.findMany({ where: { userId }, select: { key: true } });
  for (const f of files) await deleteFile(f.key);
  return files.length;
}

/** Full export of the student's own data, for transparency and portability. */
export async function exportUserData(userId: string) {
  const [
    user,
    profile,
    privacy,
    commitments,
    memories,
    subjects,
    syllabi,
    topics,
    sources,
    notes,
    flashcards,
    attempts,
    mistakes,
    revisions,
    sessions,
    experiments,
    events,
    journal,
    weeklyReviews,
    goals,
    careerInterests,
    careerReviews,
    applications,
    achievements,
    education,
    cvs,
    xp,
    badges,
    posts,
    comments,
    conversations,
  ] = await Promise.all([
    prisma.user.findUnique({ where: { id: userId }, select: { id: true, name: true, email: true, createdAt: true } }),
    prisma.studentProfile.findUnique({ where: { userId } }),
    prisma.privacySettings.findUnique({ where: { userId } }),
    prisma.commitment.findMany({ where: { userId } }),
    prisma.memoryItem.findMany({ where: { userId } }),
    prisma.subject.findMany({ where: { userId } }),
    prisma.syllabus.findMany({ where: { userId }, include: { units: true } }),
    prisma.topic.findMany({ where: { userId } }),
    prisma.source.findMany({ where: { userId }, select: { id: true, title: true, kind: true, fileName: true, url: true, createdAt: true } }),
    prisma.note.findMany({ where: { userId } }),
    prisma.flashcard.findMany({ where: { userId } }),
    prisma.practiceAttempt.findMany({ where: { userId } }),
    prisma.mistake.findMany({ where: { userId } }),
    prisma.revisionTask.findMany({ where: { userId } }),
    prisma.studySession.findMany({ where: { userId } }),
    prisma.experiment.findMany({ where: { userId } }),
    prisma.calendarEvent.findMany({ where: { userId } }),
    prisma.journalEntry.findMany({ where: { userId } }),
    prisma.weeklyReview.findMany({ where: { userId } }),
    prisma.goal.findMany({ where: { userId }, include: { milestones: true } }),
    prisma.careerInterest.findMany({ where: { userId } }),
    prisma.careerReview.findMany({ where: { userId } }),
    prisma.application.findMany({ where: { userId }, include: { opportunity: true, requirements: true } }),
    prisma.achievement.findMany({ where: { userId } }),
    prisma.educationRecord.findMany({ where: { userId } }),
    prisma.cv.findMany({ where: { userId } }),
    prisma.xpEvent.findMany({ where: { userId } }),
    prisma.userBadge.findMany({ where: { userId } }),
    prisma.post.findMany({ where: { authorId: userId } }),
    prisma.comment.findMany({ where: { authorId: userId } }),
    prisma.conversation.findMany({ where: { userId }, include: { messages: true } }),
  ]);
  return {
    exportedAt: new Date().toISOString(),
    note: "Uploaded files are not included; download them individually from Learn.",
    user,
    profile,
    privacy,
    commitments,
    memories,
    subjects,
    syllabi,
    topics,
    sources,
    notes,
    flashcards,
    practiceAttempts: attempts,
    mistakes,
    revisionTasks: revisions,
    studySessions: sessions,
    experiments,
    calendarEvents: events,
    journal,
    weeklyReviews,
    goals,
    careerInterests,
    careerReviews,
    applications,
    achievements,
    education,
    cvs,
    xpEvents: xp,
    badges,
    communityPosts: posts,
    communityComments: comments,
    conversations,
  };
}
